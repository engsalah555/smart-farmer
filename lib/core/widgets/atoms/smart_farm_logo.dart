class SmartFarmLogo extends StatelessWidget {
  final double width;
  final double height;
  final Color? color;
  final Color? detailColor;
  final String? semanticLabel;

  const SmartFarmLogo({
    super.key,
    this.width = 160,
    this.height = 84,
    this.color,
    this.detailColor,
    this.semanticLabel,
  });

  /// Factory preset for large branding surfaces (Splash, Auth)
  factory SmartFarmLogo.large({Key? key, Color? color, Color? detailColor, String? semanticLabel}) =>
      SmartFarmLogo(key: key, width: 250, height: 130, color: color, detailColor: detailColor, semanticLabel: semanticLabel);

  /// Factory preset for standard placement (Headers, Dialogs)
  factory SmartFarmLogo.medium({Key? key, Color? color, Color? detailColor, String? semanticLabel}) =>
      SmartFarmLogo(key: key, width: 160, height: 84, color: color, detailColor: detailColor, semanticLabel: semanticLabel);

  /// Factory preset for tight spaces (Bottom Nav, Mini-headers)
  factory SmartFarmLogo.compact({Key? key, Color? color, Color? detailColor, String? semanticLabel}) =>
      SmartFarmLogo(key: key, width: 100, height: 52, color: color, detailColor: detailColor, semanticLabel: semanticLabel);

  @override
  Widget build(BuildContext context) {
    // Map colors to design system tokens
    final primaryGreen = color ?? context.primary;
    final accentGreen = color ?? context.accent;
    final details = detailColor ?? context.white;

    return Semantics(
      label: semanticLabel ?? 'Smart Farm logo',
      image: true,
      excludeSemantics: true,
      child: SizedBox(
        width: width,
        height: height,
        child: CustomPaint(
          painter: _LogoPainter(
            primaryColor: primaryGreen,
            accentColor: accentGreen,
            detailColor: details,
          ),
        ),
      ),
    );
  }
}

class _LogoPainter extends CustomPainter {
  final Color primaryColor;
  final Color accentColor;
  final Color detailColor;

  _LogoPainter({required this.primaryColor, required this.accentColor, required this.detailColor});

  @override
  void paint(Canvas canvas, Size size) {
    // Scaling logic: Original SVG size is 329 x 172
    double scaleX = size.width / 329;
    double scaleY = size.height / 172;
    double scale = scaleX < scaleY ? scaleX : scaleY;

    canvas.save();
    canvas.scale(scale);

    // Optimized: Paths are pre-calculated or reused
    _drawPaths(canvas);

    canvas.restore();
  }

  void _drawPaths(Canvas canvas) {
    final primaryPaint = Paint()..color = primaryColor;
    final accentPaint = Paint()..color = accentColor;
    final detailPaint = Paint()..color = detailColor;

    // Path 1 (Small circle top) - Accent
    canvas.drawPath(_Paths.path1, accentPaint);

    // Paths 4-8 (Main Leaf & Circuits) - Primary
    canvas.drawPath(_Paths.path4, primaryPaint);
    canvas.drawPath(_Paths.path5, primaryPaint);
    canvas.drawPath(_Paths.path6, primaryPaint);
    canvas.drawPath(_Paths.path7, primaryPaint);
    canvas.drawPath(_Paths.path8, primaryPaint);

    // Path 9 (Light Green Dot) - Accent
    canvas.drawPath(_Paths.path9, accentPaint);

    // Path 10 (White/Light Details) - White
    canvas.drawPath(_Paths.path10, detailPaint);
  }

  @override
  bool shouldRepaint(covariant _LogoPainter oldDelegate) =>
      oldDelegate.primaryColor != primaryColor ||
      oldDelegate.accentColor != accentColor ||
      oldDelegate.detailColor != detailColor;
}

